// Writes src/katex-stretchy.css: every stretchy thing KaTeX draws (the arrows
// of \xrightarrow and kin, \widehat, \overrightarrow, \overbrace, …) as CSS
// masks made of KaTeX's own SVG pieces, so the editor stretches them exactly
// as the publisher does. Run after upgrading KaTeX:
//   node scripts/katex-stretchy.mjs
//
// KaTeX draws one in one to three pieces side by side, each an SVG that is
// very wide and sliced to its box (the ends keep their shape, the middle
// stretches), or one SVG scaled whole (\widehat). Each piece becomes a mask
// layer at KaTeX's own position and width.
import fs from "node:fs";
import katex from "katex";

const src = fs.readFileSync(new URL("../node_modules/katex/dist/katex.mjs", import.meta.url), "utf8");
const version = JSON.parse(fs.readFileSync(new URL("../node_modules/katex/package.json", import.meta.url), "utf8")).version;
const block = src.slice(src.indexOf("katexImagesData = {"), src.indexOf("};", src.indexOf("katexImagesData = {")));
const names = [...block.matchAll(/^\s+(\w+): \[/gm)].map((m) => m[1]).concat(["widehat", "widecheck", "widetilde", "utilde"]);

// where KaTeX puts each piece (katex.css)
const PLACE = {
  "hide-tail": "0 0 / 100% 100%",
  "halfarrow-left": "0 0 / 50.2% 100%",
  "halfarrow-right": "100% 0 / 50.2% 100%",
  "brace-left": "0 0 / 25.1% 100%",
  "brace-center": "50% 0 / 50% 100%",
  "brace-right": "100% 0 / 25.1% 100%",
};
const svgURL = (viewBox, par, paths) =>
  `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" preserveAspectRatio="${par}">${paths}</svg>`)}")`;

const rules = [];
for (const name of names) {
  let html;
  try { html = katex.renderToString(`\\${name}{abcdef}`, { throwOnError: true }); } catch { continue; } // not a command KaTeX parses
  const layers = [];
  let h = null, min = null;
  // pieces: <span class="piece" style="height:…"><svg … viewBox preserveAspectRatio><path…/></svg></span>
  for (const m of html.matchAll(/<span class="([a-z-]+)" style="([^"]*)"><svg[^>]*?height="([^"]+)" viewBox="([^"]+)" preserveAspectRatio="([^"]+)">(.*?)<\/svg>/gs)) {
    const [, cls, style, height, viewBox, par, paths] = m;
    if (!PLACE[cls]) continue;
    layers.push(`${svgURL(viewBox, par, paths)} ${PLACE[cls]} no-repeat`);
    h = height;
    min ??= /min-width:([^;]+)/.exec(style)?.[1] ?? null;
  }
  min ??= /class="katex-stretchy" style="[^"]*min-width:([^;"]+)/.exec(html)?.[1] ?? null;
  // one SVG scaled whole (\widehat, \utilde)
  if (!layers.length) {
    const m = /<svg[^>]*?width="100%" height="([^"]+)" viewBox="([^"]+)" preserveAspectRatio="none">(.*?)<\/svg>/s.exec(html);
    if (!m) continue;
    layers.push(`${svgURL(m[2], "none", m[3])} 0 0 / 100% 100% no-repeat`);
    h = m[1];
  }
  const height = parseFloat(h);
  // --st-y: an arrow's box is centred on the math axis, .25em above the baseline
  rules.push(`.pm-st-${name} { --st-h: ${h}; --st-min: ${min ?? "0"}; --st-y: ${(0.25 - height / 2).toFixed(3)}em; --st-mask: ${layers.join(", ")}; }`);
}

fs.writeFileSync(new URL("../src/katex-stretchy.css", import.meta.url), `/* Generated by scripts/katex-stretchy.mjs from KaTeX ${version}: do not edit.
   Every stretchy thing KaTeX draws, as mask layers of its own SVG pieces:
   --st-h height, --st-min least width, --st-y where the box's bottom sits for
   an arrow centred on the axis, --st-mask the layers. */
${rules.join("\n")}
`);
console.log(`${rules.length} stretchy shapes from KaTeX ${version}`);
