// Writes src/katex-symbols.js: every math-mode symbol KaTeX defines (a
// command that is one glyph), read from KaTeX's own source, so the editor
// knows the same set the publisher renders. Run after upgrading KaTeX:
//   node scripts/katex-symbols.mjs
import fs from "node:fs";

const src = fs.readFileSync(new URL("../node_modules/katex/dist/katex.mjs", import.meta.url), "utf8");
const version = JSON.parse(fs.readFileSync(new URL("../node_modules/katex/package.json", import.meta.url), "utf8")).version;

// KaTeX's groups -> the editor's classes; spacing commands and accents are not glyphs here
const CLS = { rel: "rel", bin: "bin", mathord: "ord", textord: "ord", open: "ord", close: "ord", inner: "ord", punct: "punct", op: "op" };

const out = {};
const re = /defineSymbol\(math,\s*(main|ams),\s*(\w+),\s*("(?:[^"\\]|\\.)*"|null),\s*"((?:[^"\\]|\\.)*)"(?:,\s*true)?\)/g;
for (const [, font, group, chr, name] of src.matchAll(re)) {
  const cmd = JSON.parse(`"${name}"`);
  const char = chr === "null" ? null : JSON.parse(chr);
  if (!/^\\[a-zA-Z]+$/.test(cmd) || !char || !CLS[group] || out[cmd.slice(1)]) continue;
  // [glyph, class, font ("ams" or ""), italic (letters KaTeX sets as math italic)]
  out[cmd.slice(1)] = [char, CLS[group], font === "ams" ? "ams" : "", group === "mathord" ? 1 : 0];
}

const body = Object.entries(out).sort(([a], [b]) => a.localeCompare(b))
  .map(([name, v]) => `  ${/^[a-zA-Z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)}: ${JSON.stringify(v)},`).join("\n");

// The italic correction of each glyph of KaTeX's math italic font (its
// metrics: [depth, height, italic, skew, width]), for the ones that have
// one: TeX and KaTeX add it after the glyph, so a ) or a : after a P or
// an f clears the letter's overhang.
const metrics = src.slice(src.indexOf('"Math-Italic": {'));
const italic = {};
for (const [, code, ic] of metrics.slice(0, metrics.indexOf("\n  }")).matchAll(/"(\d+)": \[[^,]+, [^,]+, ([^,]+),/g)) {
  if (Number(ic) > 0) italic[String.fromCodePoint(Number(code))] = Number(ic);
}

fs.writeFileSync(new URL("../src/katex-symbols.js", import.meta.url), `// Generated by scripts/katex-symbols.mjs from KaTeX ${version}: do not edit.
// Every math symbol KaTeX defines: name -> [glyph, class, font, italic].
export const KATEX_SYMBOLS = {
${body}
};

// The italic correction (em) of each math italic glyph that has one.
export const MATH_ITALIC = ${JSON.stringify(italic)};
`);
console.log(`${Object.keys(out).length} symbols from KaTeX ${version}`);
