export const LANGUAGES = [
  { id: "zh-TW", name: "繁體中文", strings: zh },
  { id: "en", name: "English", strings: en },
];

let strings = zh;
export let lang = "zh-TW";

export function setLang(id) {
  const found = LANGUAGES.find((l) => l.id === id) ?? LANGUAGES[0];
  lang = found.id;
  strings = found.strings;
  document.documentElement.lang = lang;
  // static labels in index.html
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}

// Traditional Chinese unless chosen otherwise in settings (⌘,).
export const defaultLang = () => "zh-TW";

export function t(key, ...args) {
  const v = strings[key] ?? zh[key];
  return typeof v === "function" ? v(...args) : v ?? key;
}
